--
-- Fixed id blocks (the app gives new rows MAX + 1, so later rows never fall inside them):
--   Quest_ID 2001-2084, Exam_ID 2001-2028, RegisID 20001-20147
--
-- Kept consistent with the app rules:
--   * students only take a course after passing its prerequisites (REQUIRES), counting the 02 seed
--     results and the results generated here (courses are filled in prerequisite order);
--   * sv104 never takes Data Structures and Algorithms, so the demo (part E) still blocks sv104;
--   * PDM (course 1), its topics 1-4 and the "DEMO - ..." exams are untouched: the demo script stays valid.
--
-- Workbench: run the whole file (lightning icon). If auto-commit is off, the COMMIT at the end saves it.
-- Without Workbench: java -jar <app>.jar --add-sample-data  (runs this file packed in the jar).
-- To remove the block only: run 04_extra_sample_data_cleanup.sql.
-- Generated by a script with a fixed random seed: every run inserts exactly the same rows.
-- ============================================================================
