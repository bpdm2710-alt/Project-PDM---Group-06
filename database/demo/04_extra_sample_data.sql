       COUNT(DISTINCT r.`RegisID`) AS registrations,
       COUNT(v.`Attempt_no`) AS attempts,
       ROUND(AVG(v.`ScorePercent`), 1) AS avg_percent,
       SUM(v.`IsPassed`) AS passed_attempts
FROM `EXAMINATION` e
LEFT JOIN `REGISTRATION` r ON r.`Exam_ID` = e.`Exam_ID`
LEFT JOIN `v_attempt_scores` v ON v.`RegisID` = r.`RegisID`
WHERE e.`Exam_ID` BETWEEN 2001 AND 2028
GROUP BY e.`Course_ID`, e.`Exam_ID`, e.`Title`, e.`Exam_date`
ORDER BY e.`Course_ID`, e.`Exam_ID`;
